// Reiser ut av Aidne og hjem, lagring i fremmed region og atlaset på mobil.
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const root = new URL('../../',import.meta.url).pathname;
const out = path.resolve(process.argv[2] || 'dist/atlas-test');
fs.mkdirSync(out,{ recursive:true });
const html=fs.readFileSync(path.join(root,'dist/index.html'),'utf8');
const server=http.createServer((req,res)=> { res.writeHead(200,{ 'Content-Type':'text/html; charset=utf-8' }); res.end(html); });
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({ executablePath:process.env.CHROME || undefined,
  args:['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required'] });
const result={ errors:[],steps:[] };
try {
  const page=await browser.newPage({ viewport:{ width:1280,height:800 } });
  page.setDefaultTimeout(90000);
  page.on('pageerror',e=>result.errors.push(e.stack || e.message));
  page.on('console',m=> { if(m.type()==='error') result.errors.push(m.text()); });
  await page.route(/cdn\.jsdelivr\.net\/npm\/three@[^/]+\/(.*)$/,async r=> {
    const sub=r.request().url().match(/three@[^/]+\/(.*)$/)[1];
    await r.fulfill({ contentType:'application/javascript',body:fs.readFileSync(path.join(root,'node_modules/three',sub)) });
  });
  await page.route(/fonts\.(googleapis|gstatic)\.com/,r=>r.fulfill({ body:'',contentType:'text/css' }));
  await page.addInitScript(()=>localStorage.setItem('svartnebb.settings.v1',JSON.stringify({ quality:'lav',music:0,sfx:0 })));
  for(const f of ['sim.js','town.js']) await page.addInitScript(fs.readFileSync(path.join(root,'tools/test',f),'utf8'));
  await page.goto(`http://127.0.0.1:${server.address().port}/DoD-Roguelite/`);
  console.log('HTML lastet');
  await page.waitForFunction(()=>window.G?.game?.title);
  console.log('Spillet er klart');
  await page.addStyleTag({ content:'*,*::before,*::after{animation-duration:0s!important;transition:none!important}' });
  await page.keyboard.press('Enter');
  await page.locator('#mi-quick').click();
  await page.waitForFunction(()=>G.state==='play'&&!G.game.wiping);
  await page.evaluate(()=> { G.debugNoEnc=true; G.game.openTravel('fristaden'); });
  await page.waitForFunction(()=>G.state==='world'&&!G.game.wiping);
  console.log('Regionkartet er åpent');
  const items=await page.evaluate(()=>({ bag:G.player.bag.map(e=>({ name:e.name,cid:e.cid,qty:e.qty })),potions:G.player.potions,pickups:G.pickups.length }));
  await page.keyboard.press('i');
  await page.waitForFunction(()=>G.state==='inventory');
  assert.equal(await page.locator('[data-drop="ground"]').count(),0);
  await page.evaluate(()=>G.inv.doDrop({ kind:'belt',e:{} },'ground'));
  assert.deepEqual(await page.evaluate(()=>({ bag:G.player.bag.map(e=>({ name:e.name,cid:e.cid,qty:e.qty })),potions:G.player.potions,pickups:G.pickups.length })),items);
  await page.keyboard.press('i');
  await page.waitForFunction(()=>G.state==='world');
  const start=await page.evaluate(()=>({ silver:G.player.silver,clock:G.run.clock,seen:G.run.world.seen.slice() }));
  await page.locator('#btn-w-atlas').click();
  assert.equal(await page.locator('#atlas-country option').count(),31);
  await page.locator('#atlas-country').selectOption('caddo');
  console.log('Atlaset er åpent');
  await page.evaluate(()=> { G.atlasFrames=0; G.atlasFrameStart=performance.now(); G.savedRender=G.composer.render; G.composer.render=function(...args) { G.atlasFrames++; return G.savedRender.apply(this,args); }; });
  await page.waitForTimeout(800);
  const frames=await page.evaluate(()=> { G.composer.render=G.savedRender; return { count:G.atlasFrames,ms:performance.now()-G.atlasFrameStart }; });
  console.log('Atlasets bakgrunn:',JSON.stringify(frames));
  assert.ok(frames.count<=Math.ceil(frames.ms/125)+1,'3D-bakgrunnen skal tegnes høyst åtte ganger i sekundet på atlaset: '+JSON.stringify(frames));
  result.background=frames;
  await page.screenshot({ path:path.join(out,'atlas-caddo.png'),timeout:90000 });
  await page.evaluate(()=> { const b=document.querySelector('#btn-atlas-travel'); b.click(); b.click(); });
  await page.waitForFunction(()=>G.state==='world'&&G.run.world.region==='caddo'&&!G.game.wiping);
  const caddo=await page.evaluate(()=>({ silver:G.player.silver,clock:G.run.clock,journeys:G.run.world.journeys.length,title:document.querySelector('#w-map-title').textContent }));
  assert.equal(caddo.silver,start.silver-20); assert.equal(caddo.journeys,1);
  assert.ok(Math.abs(caddo.clock-start.clock-10)<0.02); assert.equal(caddo.title,'Caddo');
  result.steps.push({ name:'Fristaden til Arno, ett trekk ved dobbeltklikk',...caddo });
  console.log('Ankom Caddo');
  await page.screenshot({ path:path.join(out,'caddo-kart.png'),timeout:90000 });
  // Bruk samme serialisering som autolagringen, og behold et øyeblikk fra Arno.
  const saved=await page.evaluate(()=> {
    const all=JSON.parse(localStorage.getItem('svartnebb.saves.v1'));
    all['1']=all.auto; localStorage.setItem('svartnebb.saves.v1',JSON.stringify(all));
    return { onWorld:all.auto.onWorld,region:all.auto.run.world.region,area:all.auto.run.areaSpec.id };
  });
  assert.deepEqual(saved,{ onWorld:true,region:'caddo',area:'arno' });
  await page.locator('#btn-w-enter').click();
  await page.waitForFunction(()=>G.state==='play'&&G.dungeon.L?.place==='arno'&&!G.game.wiping);
  await page.evaluate(()=> { setHour(12); talk('v_arno_bonde'); });
  assert.ok((await page.locator('#dlg-text').innerText()).includes('magien'));
  await page.screenshot({ path:path.join(out,'arno-samtale.png'),timeout:90000 });
  result.steps.push({ name:'Arno har lokale folk og Caddos skikker i samtalen' });
  await page.evaluate(()=> { G.talk.close(); G.game.openWorld(); });
  await page.locator('#btn-w-atlas').click();
  await page.locator('#atlas-country').selectOption('trakorien');
  await page.locator('#atlas-mode').selectOption('crew');
  await page.locator('#btn-atlas-travel').click();
  await page.waitForFunction(()=>G.state==='world'&&G.run.world.region==='trakorien'&&!G.game.wiping);
  await page.screenshot({ path:path.join(out,'trakorien-kart.png'),timeout:90000 });
  await page.evaluate(()=>G.game.loadSave('1'));
  await page.waitForFunction(()=>G.state==='world'&&G.run.world.region==='caddo'&&!G.game.wiping);
  assert.equal(await page.evaluate(()=>G.run.areaSpec.id),'arno');
  result.steps.push({ name:'Lagring fra Arno gjenopprettes etter tur til Trakorien' });
  await page.evaluate(()=> { G.player.silver=0; });
  await page.locator('#btn-w-atlas').click();
  await page.locator('#atlas-country').selectOption('aidne');
  await page.locator('#atlas-mode').selectOption('passenger');
  assert.equal(await page.locator('#btn-atlas-travel').isDisabled(),true);
  await page.locator('#atlas-mode').selectOption('crew');
  await page.locator('#btn-atlas-travel').click();
  await page.waitForFunction(()=>G.state==='world'&&G.run.world.region==='aidne'&&!G.game.wiping);
  assert.equal(await page.evaluate(()=>G.player.silver),0);
  const home=await page.evaluate(()=>({ x:G.run.world.x,y:G.run.world.y,seen:G.run.world.seen.slice() }));
  assert.deepEqual([home.x,home.y],[35,7]);
  for(let i=0;i<start.seen.length;i++) assert.ok(home.seen[i]>=start.seen[i]);
  result.steps.push({ name:'Hyre hjem uten penger bevarer utforskingen i Aidne' });
  await page.locator('#btn-w-atlas').click();
  await page.locator('#atlas-country').selectOption('akrogal');
  assert.equal(await page.locator('#btn-atlas-find').isVisible(),true);
  await page.setViewportSize({ width:390,height:844 });
  await page.screenshot({ path:path.join(out,'atlas-mobil.png'),fullPage:true,timeout:90000 });
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(overflow,false,'atlaset renner ut av mobilskjermen');
  await page.locator('#btn-atlas-find').click();
  await page.waitForFunction(()=>G.state==='world');
  assert.ok(await page.evaluate(()=>G.worldview.sel?.length===2));
  await page.locator('#btn-w-go').click();
  await page.waitForFunction(()=>G.state==='atlas'&&!G.worldview.moving);
  assert.equal(await page.locator('#atlas-country').inputValue(),'jorpagna');
  await page.locator('#btn-atlas-travel').click();
  await page.waitForFunction(()=>G.state==='world'&&G.run.world.region==='jorpagna'&&!G.game.wiping);
  assert.equal(await page.evaluate(()=>G.player.silver),0);
  result.steps.push({ name:'Fysisk ferd til grenseveien og over til Jorpagna' });
  await page.setViewportSize({ width:844,height:390 });
  await page.locator('#btn-w-atlas').click();
  await page.screenshot({ path:path.join(out,'atlas-mobil-liggende.png'),timeout:90000 });
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>G.state==='world');
  result.steps.push({ name:'Mobil, finn avgangen og Escape tilbake til regionkartet' });
  assert.deepEqual(result.errors,[]);
} finally {
  fs.writeFileSync(path.join(out,'resultat.json'),JSON.stringify(result,null,2));
  await browser.close(); server.close();
}
console.log(JSON.stringify(result,null,2));
